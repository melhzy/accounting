"""Multi-seed train/valid/test splitter for robustness-aware fine-tuning.

Produces N independent 80/10/10 splits of `eval/spiceland9e.jsonl`, one per
deterministic seed generated by the `seedhash` package
(https://pypi.org/project/seedhash/). Each split honors:

  - **Scenario grouping** — all records sharing a scenario fingerprint land
    in the same split (prevents holdout-via-memorization leakage of
    Cupid Construction / Thompson TV inventory-style multi-Q scenarios).
  - **Bloom stratification** — within each Bloom level, scenarios are
    shuffled (with the per-seed random.Random instance) and then cut 80/10/10.
  - **Determinism** — same `seedhash_input` + `n_seeds` always yields byte-
    identical split files.

Outputs:
  eval/sft/splits/manifest.json                            overall index
  eval/sft/splits/seed_<i>__<seedNNNNNN>/train.jsonl
  eval/sft/splits/seed_<i>__<seedNNNNNN>/valid.jsonl
  eval/sft/splits/seed_<i>__<seedNNNNNN>/test.jsonl
  eval/sft/splits/seed_<i>__<seedNNNNNN>/manifest.json     per-seed stats

Train + valid feed the fine-tuner (valid used for early-stopping / lr
scheduling); test is held out for post-training evaluation only.

Run from repo root:
  python eval/split_multi_seed.py
"""
from __future__ import annotations

import hashlib
import json
import random
import sys
from collections import Counter, defaultdict
from datetime import datetime, timezone
from pathlib import Path

import seedhash

# Reuse the rendering helpers from the shared format module so no two
# pipeline scripts ever drift in chat-template output.
sys.path.insert(0, str(Path(__file__).resolve().parent))
from _format import (  # type: ignore  noqa: E402
    SYSTEM_PROMPT,
    build_messages,
    is_worked_solution,
    scenario_fingerprint,
    should_skip,
)

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

# ============================================================================
# CONFIG — edit these to control the multi-split run
# ============================================================================
REPO_ROOT = Path(__file__).resolve().parents[1]
IN_JSONL = REPO_ROOT / "eval" / "spiceland9e.jsonl"
OUT_DIR = REPO_ROOT / "eval" / "sft" / "splits"

# String fed to seedhash to derive the deterministic seed sequence. Change
# this when you want a fresh sequence of seeds (e.g. across major dataset
# revisions); keep it stable across runs to reproduce the same splits.
SEEDHASH_INPUT = "spiceland9e-finetune-robustness-2026-05-19"
N_SEEDS = 5

# Train/valid/test ratios. Must sum to 1.0.
SPLIT_FRACTIONS = {"train": 0.80, "valid": 0.10, "test": 0.10}

# Tokenizer pin — fill before launching a fine-tune.
TOKENIZER_PIN: str | None = None


# ============================================================================
# Splitting
# ============================================================================

def modal_bloom(records: list[dict]) -> str:
    """Pick the dominant Bloom level for a scenario group. Ties broken by
    the first record's primary Bloom."""
    blooms = [r.get("bloom") or ["Unknown"] for r in records]
    primary = [b[0] if b else "Unknown" for b in blooms]
    if not primary:
        return "Unknown"
    counts = Counter(primary)
    top_count = counts.most_common(1)[0][1]
    for p in primary:  # tie-break by first occurrence
        if counts[p] == top_count:
            return p
    return primary[0]


def stratified_split(
    scenarios_by_bloom: dict[str, list[str]],
    rng: random.Random,
    fractions: dict[str, float],
) -> dict[str, str]:
    """For each Bloom stratum: shuffle scenario fingerprints, then cut into
    train/valid/test by `fractions`. Returns {scenario_fp: bucket}.

    Tiny strata (< 3 scenarios) put everything in train to avoid empty
    valid/test on rare Bloom levels — caller can filter Vera's slice
    accordingly.
    """
    assignment: dict[str, str] = {}
    bucket_order = list(fractions.keys())  # train, valid, test
    for bloom, fps in scenarios_by_bloom.items():
        fps_shuffled = fps[:]
        rng.shuffle(fps_shuffled)
        n = len(fps_shuffled)
        if n < 3:
            for fp in fps_shuffled:
                assignment[fp] = "train"
            continue
        n_train = max(1, round(n * fractions["train"]))
        n_valid = max(1, round(n * fractions["valid"]))
        # Test gets the remainder so the splits sum exactly
        n_test = max(1, n - n_train - n_valid)
        # Re-balance if rounding produced overcount
        while n_train + n_valid + n_test > n:
            if n_train > n_valid and n_train > n_test:
                n_train -= 1
            elif n_valid >= n_test:
                n_valid -= 1
            else:
                n_test -= 1
        sizes = {"train": n_train, "valid": n_valid, "test": n_test}
        i = 0
        for bucket in bucket_order:
            for fp in fps_shuffled[i : i + sizes[bucket]]:
                assignment[fp] = bucket
            i += sizes[bucket]
    return assignment


def build_record_envelope(rec: dict, scenario_id: str, scenario_size: int) -> dict:
    """Build the SFT envelope (messages + meta) — same format as build_training_set."""
    messages = build_messages(rec)
    assistant_msg = messages[-1]["content"]
    primary_bloom = (rec.get("bloom") or ["Unknown"])[0]
    return {
        "messages": messages,
        "meta": {
            "id": rec["id"],
            "chapter": rec["chapter"],
            "question_number": rec["question_number"],
            "type": rec.get("type"),
            "bloom": rec.get("bloom") or [],
            "primary_bloom": primary_bloom,
            "difficulty": rec.get("difficulty"),
            "lo_code": (rec.get("lo") or {}).get("code"),
            "topic": rec.get("topic"),
            "has_tables": bool(rec.get("tables")),
            "n_tables": len(rec.get("tables") or []),
            "has_explanation": bool(rec.get("explanation")),
            "scenario_id": scenario_id,
            "scenario_group_size": scenario_size,
            "has_worked_solution": is_worked_solution(assistant_msg),
            "assistant_length": len(assistant_msg),
            "source_workbook": rec.get("source_workbook"),
            "source_row": rec.get("source_row"),
        },
    }


def run_one_seed(
    seed_int: int,
    seed_index: int,
    eligible: list[dict],
    fp_to_records: dict[str, list[dict]],
    fp_to_modal_bloom: dict[str, str],
    in_jsonl_sha: str,
) -> dict:
    """Run a single split for one seed. Writes files; returns the per-seed manifest."""
    seed_dir_name = f"seed_{seed_index:02d}__{seed_int}"
    seed_dir = OUT_DIR / seed_dir_name
    seed_dir.mkdir(parents=True, exist_ok=True)

    # Group scenarios by their modal Bloom level
    scenarios_by_bloom: dict[str, list[str]] = defaultdict(list)
    for fp, bloom in fp_to_modal_bloom.items():
        scenarios_by_bloom[bloom].append(fp)
    # Sort fps within each bloom so the shuffle is reproducible across machines
    for bloom in scenarios_by_bloom:
        scenarios_by_bloom[bloom].sort()

    rng = random.Random(seed_int)
    fp_to_bucket = stratified_split(scenarios_by_bloom, rng, SPLIT_FRACTIONS)

    splits: dict[str, list[dict]] = {k: [] for k in SPLIT_FRACTIONS}
    bloom_by_split: dict[str, Counter] = defaultdict(Counter)
    chapter_by_split: dict[str, Counter] = defaultdict(Counter)
    type_by_split: dict[str, Counter] = defaultdict(Counter)
    worked_by_split: dict[str, Counter] = defaultdict(Counter)
    scenarios_by_split_set: dict[str, set] = defaultdict(set)

    for fp, group in fp_to_records.items():
        bucket = fp_to_bucket[fp]
        scenarios_by_split_set[bucket].add(fp)
        for rec in group:
            env = build_record_envelope(rec, fp, len(group))
            splits[bucket].append(env)
            m = env["meta"]
            bloom_by_split[bucket][m["primary_bloom"]] += 1
            chapter_by_split[bucket][m["chapter"]] += 1
            type_by_split[bucket][m["type"] or "Unknown"] += 1
            worked_by_split[bucket][m["has_worked_solution"]] += 1

    # Stable sort + write split files
    file_shas: dict[str, str] = {}
    for bucket, records in splits.items():
        records.sort(key=lambda r: r["meta"]["id"])
        path = seed_dir / f"{bucket}.jsonl"
        with path.open("w", encoding="utf-8", newline="\n") as fh:
            for r in records:
                fh.write(json.dumps(r, ensure_ascii=False, sort_keys=True))
                fh.write("\n")
        file_shas[bucket] = hashlib.sha256(path.read_bytes()).hexdigest()

    # Cross-split overlap regression check (must be 0)
    seen_fp_to_bucket: dict[str, str] = {}
    cross_split_overlap = 0
    for bucket, records in splits.items():
        for r in records:
            fp = r["meta"]["scenario_id"]
            prior = seen_fp_to_bucket.get(fp)
            if prior is not None and prior != bucket:
                cross_split_overlap += 1
            seen_fp_to_bucket[fp] = bucket

    seed_manifest = {
        "seed_index": seed_index,
        "seed_int": seed_int,
        "seedhash_input": SEEDHASH_INPUT,
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "source_jsonl_sha256": in_jsonl_sha,
        "split_fractions": SPLIT_FRACTIONS,
        "split_counts": {k: len(v) for k, v in splits.items()},
        "scenarios_per_split": {k: len(v) for k, v in scenarios_by_split_set.items()},
        "cross_split_scenario_overlap": cross_split_overlap,  # MUST be 0
        "worked_solution_by_split": {
            k: {"worked": v.get(True, 0), "stub": v.get(False, 0)}
            for k, v in worked_by_split.items()
        },
        "primary_bloom_by_split": {k: dict(v) for k, v in bloom_by_split.items()},
        "chapter_by_split": {k: dict(v) for k, v in chapter_by_split.items()},
        "type_by_split": {k: dict(v) for k, v in type_by_split.items()},
        "file_sha256": file_shas,
        "tokenizer_pin": TOKENIZER_PIN,
        "system_prompt": SYSTEM_PROMPT,
    }
    (seed_dir / "manifest.json").write_text(
        json.dumps(seed_manifest, indent=2, ensure_ascii=False),
        encoding="utf-8",
    )
    return seed_manifest


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    # Load eligible records once
    eligible: list[dict] = []
    skipped: Counter = Counter()
    total_in = 0
    for line in IN_JSONL.read_text(encoding="utf-8").splitlines():
        total_in += 1
        rec = json.loads(line)
        skip_reason = should_skip(rec)
        if skip_reason:
            skipped[skip_reason] += 1
            continue
        eligible.append(rec)

    # Compute scenario groups once (identical across seeds)
    fp_to_records: dict[str, list[dict]] = defaultdict(list)
    for rec in eligible:
        fp = scenario_fingerprint(rec["prompt"])
        fp_to_records[fp].append(rec)
    fp_to_modal_bloom = {fp: modal_bloom(group) for fp, group in fp_to_records.items()}

    # Generate seeds via seedhash
    gen = seedhash.SeedHashGenerator(SEEDHASH_INPUT)
    seeds = gen.generate_seeds(N_SEEDS)

    in_jsonl_sha = hashlib.sha256(IN_JSONL.read_bytes()).hexdigest()

    print(f"Loaded {len(eligible)} eligible records ({total_in} total, "
          f"{sum(skipped.values())} skipped: {dict(skipped) or '—'})")
    print(f"Scenario groups: {len(fp_to_records)}  |  largest={max(len(g) for g in fp_to_records.values())}")
    print(f"Generating {N_SEEDS} seeds from seedhash input "
          f"{SEEDHASH_INPUT!r}: {seeds}")
    print()

    per_seed_manifests: list[dict] = []
    for i, seed_int in enumerate(seeds):
        print(f"[seed {i:02d}] {seed_int} ...")
        sm = run_one_seed(
            seed_int=seed_int,
            seed_index=i,
            eligible=eligible,
            fp_to_records=fp_to_records,
            fp_to_modal_bloom=fp_to_modal_bloom,
            in_jsonl_sha=in_jsonl_sha,
        )
        per_seed_manifests.append(sm)
        sc = sm["split_counts"]
        ws = sm["worked_solution_by_split"]
        print(
            f"           counts: train={sc['train']} valid={sc['valid']} test={sc['test']}  "
            f"| worked: tr={ws['train']['worked']} va={ws['valid']['worked']} te={ws['test']['worked']}  "
            f"| overlap={sm['cross_split_scenario_overlap']}"
        )

    overall = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "source_jsonl": str(IN_JSONL.relative_to(REPO_ROOT)),
        "source_jsonl_sha256": in_jsonl_sha,
        "seedhash_input": SEEDHASH_INPUT,
        "seedhash_package_version": seedhash.__version__ if hasattr(seedhash, "__version__") else "unknown",
        "n_seeds": N_SEEDS,
        "split_fractions": SPLIT_FRACTIONS,
        "input_records": total_in,
        "eligible_records": len(eligible),
        "skipped": dict(skipped),
        "n_scenarios": len(fp_to_records),
        "tokenizer_pin": TOKENIZER_PIN,
        "system_prompt": SYSTEM_PROMPT,
        "seeds": [
            {
                "seed_index": sm["seed_index"],
                "seed_int": sm["seed_int"],
                "split_counts": sm["split_counts"],
                "scenarios_per_split": sm["scenarios_per_split"],
                "cross_split_scenario_overlap": sm["cross_split_scenario_overlap"],
                "file_sha256": sm["file_sha256"],
            }
            for sm in per_seed_manifests
        ],
    }
    (OUT_DIR / "manifest.json").write_text(
        json.dumps(overall, indent=2, ensure_ascii=False), encoding="utf-8"
    )
    print()
    print(f"wrote {OUT_DIR / 'manifest.json'}")


if __name__ == "__main__":
    main()
